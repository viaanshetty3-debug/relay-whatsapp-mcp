import test from 'node:test';
import assert from 'node:assert/strict';
import { readFileSync } from 'node:fs';
import { createServer } from 'node:http';
import { randomUUID } from 'node:crypto';
import { JSDOM, VirtualConsole } from 'jsdom';
import { Store } from '../src/store.js';
import { DemoWhatsApp } from '../src/demo.js';
import { Bridge } from '../src/tools.js';
import { createApp } from '../src/server.js';
const sleep=ms=>new Promise(r=>setTimeout(r,ms));
async function until(fn,message){for(let i=0;i<100;i++){if(fn())return;await sleep(20);}throw new Error(message);}
test('dashboard logs in, renders chats, sends and edits, saves drafts, schedules, searches, and locks',async t=>{
  const store=new Store(':memory:'),server=createServer();
  server.listen(0,'127.0.0.1');await new Promise(r=>server.once('listening',r));
  const port=server.address().port,base='http://127.0.0.1:'+port;
  const config={port,base,token:'test'.repeat(16),allowed:new Set(),demo:true,readOnly:false};
  const wa=new DemoWhatsApp(store,config),bridge=new Bridge(store,wa,config);server.on('request',createApp(bridge,config));
  const errors=[],vc=new VirtualConsole();vc.on('jsdomError',e=>errors.push(e.message));
  const dom=new JSDOM(readFileSync(new URL('../public/index.html',import.meta.url),'utf8'),{url:base,runScripts:'outside-only',virtualConsole:vc});
  const w=dom.window,d=w.document;
  w.fetch=(url,opts)=>fetch(base+url,opts);w.TextDecoder=TextDecoder;w.AbortController=AbortController;w.confirm=()=>true;w.prompt=()=>null;
  w.HTMLElement.prototype.scrollIntoView=()=>{};
  w.HTMLDialogElement.prototype.showModal=function(){this.open=true;};w.HTMLDialogElement.prototype.close=function(){this.open=false;};
  Object.defineProperty(w.crypto,'randomUUID',{value:randomUUID});
  t.after(async()=>{d.querySelector('#logout').click();await sleep(20);w.close();server.closeAllConnections();await new Promise(r=>server.close(r));store.close();});
  w.eval(readFileSync(new URL('../public/app.js',import.meta.url),'utf8'));
  const $=s=>d.querySelector(s),click=s=>$(s).click();
  $('#token').value=config.token;$('#login-form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>!$('#workspace').hidden && d.querySelectorAll('.chat-item').length===3,'Login failed');
  click('.chat-item');await until(()=>d.querySelectorAll('.message').length===3,'Chat failed to render');
  $('#message-input').value='Sent from the dashboard';
  const submit=new w.Event('submit',{bubbles:true,cancelable:true});$('#composer').dispatchEvent(submit);assert.equal(submit.defaultPrevented,true);
  await until(()=>$('#messages').textContent.includes('Sent from the dashboard'),'Send failed');
  const message=[...d.querySelectorAll('.message')].find(m=>m.textContent.includes('Sent from the dashboard'));
  message.querySelector('[data-action="edit"]').click();await until(()=>$('#send').textContent.includes('Save edit'),'Edit selection failed');
  $('#message-input').value='Edited from the dashboard';$('#composer').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>$('#messages').textContent.includes('Edited from the dashboard'),'Edit failed');
  $('#message-input').value='My draft';click('#save-draft');await until(()=>store.drafts().length===1,'Draft save failed');
  click('[data-view="drafts"]');await until(()=>$('#draft-list').textContent.includes('My draft'),'Draft page failed');
  click('[data-open-draft]');await until(()=>$('#message-input').value==='My draft'&&!$('#view-inbox').hidden,'Draft continuation failed');
  click('#schedule');assert.equal($('#schedule-dialog').open,true);$('#schedule-form').dispatchEvent(new w.Event('submit',{bubbles:true,cancelable:true}));
  await until(()=>store.jobs().length===1,'Scheduling failed');click('[data-view="scheduled"]');await until(()=>$('#scheduled-list').textContent.includes('My draft'),'Schedule list failed');
  click('[data-cancel]');await until(()=>store.jobs()[0].status==='cancelled','Cancel failed');
  click('[data-view="inbox"]');w.prompt=()=>'Edited from the dashboard';click('#global-search');await until(()=>!$('#search-results').hidden&&$('#search-results').textContent.includes('Edited from the dashboard'),'Search failed');
  click('[data-view="connections"]');assert.match($('#claude-config').textContent,/[\\/]+bin[\\/]+relay-whatsapp-mcp\.mjs/);assert.ok($('#mcp-url').textContent.endsWith('/mcp'));
  click('[data-view="tools"]');assert.equal(d.querySelectorAll('.tool-card').length,38);click('#run-tool');await until(()=>$('#tool-result').textContent.includes('connected'),'Tool runner failed');
  assert.deepEqual(errors,[]);
  click('#logout');assert.equal($('#workspace').hidden,true);assert.equal(w.sessionStorage.getItem('relay-token'),null);
});
